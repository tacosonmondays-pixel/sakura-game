// Direct live load + patch gift claim, no local modules. node direct.mjs WxH shotsDir
import { launchChromium } from '/home/user/sakura-game/e2e/browser.mjs';
const [W, H] = process.argv[2].split('x').map(Number);
const SHOTS = process.argv[3];
const LIVE = 'https://tacosonmondays-pixel.github.io/sakura-game/';
const { browser, label } = await launchChromium();
console.log('browser', label);
const touch = W < 1000;
const ctx = await browser.newContext({ viewport: { width: W, height: H }, hasTouch: touch, isMobile: touch, deviceScaleFactor: 1 });
const page = await ctx.newPage();
const errs = []; const reqs = []; const failed = [];
page.on('pageerror', (e) => errs.push('pageerror ' + e.message));
page.on('console', (m) => { if (m.type() === 'error') errs.push('console ' + m.text()); });
page.on('requestfailed', (r) => failed.push(`${r.url()} ${r.failure()?.errorText}`));
page.on('response', (r) => reqs.push([r.status(), r.url()]));
const fails = []; const check = (c, m) => { console.log(`  ${c ? 'ok  ' : 'FAIL'} ${m}`); if (!c) fails.push(m); };
const gemsOf = (t) => Number(String(t).replace(/[^\d]/g, ''));
const tap = async (loc) => { await (touch ? loc.tap({ timeout: 15000 }) : loc.click({ timeout: 15000 })); await page.waitForTimeout(250); };
const url = `${LIVE}?online=local&onboarding=0#/lobby`;
await page.goto(url, { waitUntil: 'load' });
await page.waitForFunction(() => window.__sakura?.store?.profile, null, { timeout: 60000 });
const later = await page.waitForSelector('[data-testid="beta-gift-later"]', { timeout: 15000 }).catch(() => null);
if (later) { await later.click({ force: true }); await page.waitForSelector('.bg-gift-modal', { state: 'detached', timeout: 10000 }).catch(() => {}); }
await page.waitForTimeout(1500);
const ver = await page.evaluate(() => fetch('version.json', { cache: 'no-store' }).then((r) => r.json()));
check(ver.version === '0.1.72' && ver.build === 'b207fe9a36af' && ver.sim === 'e4001588f40b', `version.json ${JSON.stringify(ver)}`);
const overflow = await page.evaluate(() => document.documentElement.scrollWidth - innerWidth);
check(overflow <= 0, `no horizontal overflow (${overflow})`);
const gemPill = page.locator('.home-top [data-testid="gems"]').first();
await gemPill.waitFor({ timeout: 15000 });
await page.evaluate(() => document.querySelectorAll('.toast, .jn-toast, .ach-toast').forEach((n) => n.remove()));
const gems0 = gemsOf(await gemPill.innerText());
await tap(page.locator('[data-testid="top-menu"]'));
await tap(page.locator('[data-testid="menu-sheet"] [data-testid="shortcut-notice"]'));
await page.waitForSelector('.lb-notice-modal', { timeout: 10000 });
await tap(page.locator('[data-testid="notice-patch"]'));
await page.waitForSelector('.lb-patch-list', { timeout: 10000 });
const top = await page.evaluate(() => document.querySelector('.lb-patch')?.innerText || '');
const count = await page.locator('.lb-patch').count();
check(/0\.1\.72/.test(top) && /New Staff Models and a Fire Tornado/.test(top), `top patch note is v0.1.72 "New Staff Models and a Fire Tornado" (${count} versions)`);
console.log('    top:', top.split('\n').slice(0, 3).join(' | '));
if (SHOTS) await page.screenshot({ path: `${SHOTS}/01-patch-note-v0172-${W}x${H}.jpg`, type: 'jpeg', quality: 72 });
const claim = page.locator('[data-testid="patch-claim-v0.1.72"]');
check(await claim.count() === 1, 'Claim button for v0.1.72 shown');
await tap(claim);
await page.waitForTimeout(1200);
check(await page.locator('[data-testid="patch-claimed-v0.1.72"]').count() === 1 && await claim.count() === 0, 'v0.1.72 turns into Claimed ✓');
await page.keyboard.press('Escape').catch(() => {});
await page.evaluate(() => document.querySelectorAll('.modal-overlay').forEach((o) => o.remove()));
await page.waitForTimeout(800);
const gems1 = gemsOf(await gemPill.innerText());
check(gems1 - gems0 === 100, `gems +100 (${gems0} → ${gems1})`);
const again = await page.evaluate(() => window.__sakura.store.profile.patchGifts?.['v0.1.72']);
check(!!again, `profile.patchGifts['v0.1.72'] stored (${JSON.stringify(again)})`);
await page.evaluate(() => window.__sakura.store.saveNow?.());
await page.waitForTimeout(500);
await page.reload({ waitUntil: 'load' });
await page.waitForFunction(() => window.__sakura?.store?.profile, null, { timeout: 60000 });
await page.waitForTimeout(1500);
await page.evaluate(() => document.querySelectorAll('.modal-overlay, .toast, .jn-toast, .ach-toast').forEach((n) => n.remove()));
const gems2 = gemsOf(await page.locator('.home-top [data-testid="gems"]').first().innerText());
check(gems2 === gems1, `after reload gems still ${gems2}`);
await tap(page.locator('[data-testid="top-menu"]'));
await tap(page.locator('[data-testid="menu-sheet"] [data-testid="shortcut-notice"]'));
await page.waitForSelector('.lb-notice-modal', { timeout: 10000 });
await tap(page.locator('[data-testid="notice-patch"]'));
await page.waitForSelector('.lb-patch-list', { timeout: 10000 });
check(await page.locator('[data-testid="patch-claimed-v0.1.72"]').count() === 1 && await page.locator('[data-testid="patch-claim-v0.1.72"]').count() === 0, 'after reload: still Claimed ✓, no Claim button (claimable once)');
const supa = reqs.filter(([, u]) => /supabase/.test(u)).length;
const bad = reqs.filter(([s]) => s >= 400);
check(errs.length === 0, `no page/console errors${errs.length ? ': ' + errs.join(' || ') : ''}`);
check(bad.length === 0 && failed.length === 0, `requests ${reqs.length}: non-200 ${bad.length}, failed ${failed.length} ${JSON.stringify([...bad, ...failed].slice(0, 5))}`);
const hosts = {}; for (const [, u] of reqs) { const h = new URL(u).host; hosts[h] = (hosts[h] || 0) + 1; }
console.log('    hosts', JSON.stringify(hosts), 'supabase', supa);
await browser.close();
console.log(`RESULT ${W}x${H}: ${fails.length ? 'FAIL ' + fails.length : 'PASS'}`);
process.exit(fails.length ? 1 : 0);
