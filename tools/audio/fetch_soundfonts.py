#!/usr/bin/env python3
"""Fetch the soundfonts of the `cleared` palette into the gitignored cache and build our chip font.

    python tools/audio/fetch_soundfonts.py [--from <git url or local clone>] [--skip-gu]

* GeneralUser GS v2.0.3 by S. Christian Collins (License v2.0: unrestricted music creation, please do not
  hot-link the download). Fetched with plain `git` from the author's official repository, pinned to a
  commit and checked against a pinned SHA-256. (The GitHub releases API is blocked in some sandboxes; git
  is not.) Ends up in tools/audio/cache/sf2/GeneralUser-GS.sf2 with its LICENSE next to it.
* FluidR3_GM (MIT, installed by the fluid-soundfont-gm package) is the fallback when GeneralUser GS is
  missing: palettes name it as `fallback`.
* sakura-chip.sf2 (ours, CC0) is generated by make_chip_sf2.py.

Soundfont binaries never enter git (.gitignore: tools/audio/cache/, *.sf2).
"""
import argparse
import hashlib
import shutil
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from sakura_audio.paths import CACHE, SF2_CACHE  # noqa: E402

GU_REPO = 'https://github.com/mrbumpy409/generaluser-gs'
GU_COMMIT = '684543d5e5efaef08d02be50dcda8d552478fa60'          # 2026-02-23, "update documentation to r6" (v2.0.3)
GU_FILE = 'GeneralUser-GS.sf2'
GU_SIZE = 32319396
GU_SHA256 = '9575028c7a1f589f5770fccc8cff2734566af40cd26ed836944e9a5152688cfe'   # verified 2026-10-08
FLUID_R3 = Path('/usr/share/sounds/sf2/FluidR3_GM.sf2')


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, 'rb') as f:
        for block in iter(lambda: f.read(1 << 20), b''):
            h.update(block)
    return h.hexdigest()


def run(cmd, **kw):
    print('  $', ' '.join(str(c) for c in cmd))
    return subprocess.run(cmd, check=True, timeout=kw.pop('timeout', 600), **kw)


def fetch_generaluser(source: str = GU_REPO) -> Path:
    dest = SF2_CACHE / GU_FILE
    if dest.exists() and dest.stat().st_size == GU_SIZE and (GU_SHA256 is None or sha256(dest) == GU_SHA256):
        print(f'GeneralUser GS: already in cache ({dest})')
        return dest
    repo = CACHE / 'generaluser-gs'
    if not (repo / '.git').exists():
        repo.parent.mkdir(parents=True, exist_ok=True)
        run(['git', 'clone', '--depth', '1', '--filter=blob:none', '--no-checkout', source, str(repo)])
    run(['git', '-C', str(repo), 'fetch', '--depth', '1', 'origin', GU_COMMIT])
    run(['git', '-C', str(repo), 'checkout', GU_COMMIT, '--', GU_FILE, 'documentation/LICENSE.txt'])
    src = repo / GU_FILE
    size = src.stat().st_size
    if size != GU_SIZE:
        raise SystemExit(f'GeneralUser GS: unexpected size {size} (pinned {GU_SIZE})')
    digest = sha256(src)
    if GU_SHA256 and digest != GU_SHA256:
        raise SystemExit(f'GeneralUser GS: SHA-256 mismatch {digest} (pinned {GU_SHA256})')
    SF2_CACHE.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(src, dest)
    shutil.copyfile(repo / 'documentation' / 'LICENSE.txt', SF2_CACHE / 'GeneralUser-GS.LICENSE.txt')
    print(f'GeneralUser GS: {dest} ({size:,} bytes, sha256 {digest})')
    return dest


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--from', dest='source', default=GU_REPO, help='git URL or local clone of generaluser-gs')
    ap.add_argument('--skip-gu', action='store_true', help='only build the chip font')
    a = ap.parse_args(argv)
    if not a.skip_gu:
        try:
            fetch_generaluser(a.source)
        except (subprocess.SubprocessError, OSError) as e:
            print(f'GeneralUser GS: fetch failed ({e}); palettes fall back to {FLUID_R3}')
    print(f'FluidR3 GM fallback: {"present" if FLUID_R3.exists() else "MISSING (apt install fluid-soundfont-gm)"}')
    import make_chip_sf2
    make_chip_sf2.main([])


if __name__ == '__main__':
    main()
